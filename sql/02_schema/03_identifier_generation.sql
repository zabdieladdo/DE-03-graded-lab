-- DE-03: Kloud Kart
-- Stage 02.5: Concurrency-safe identifier generation
--
-- Purpose:
-- Enable automatic identifier allocation while
-- preserving all historical primary key values.
--
-- Decision reference: D023.

\set ON_ERROR_STOP on
\pset pager off
\timing on

BEGIN;

-- Prevent concurrent writes while determining
-- the starting values and modifying the schema.

LOCK TABLE orders, order_items, inventory_log
    IN ACCESS EXCLUSIVE MODE;

-- Calculate starting values dynamically.

SELECT
    GREATEST(
        COALESCE(MAX(order_id)::bigint, 0) + 1,
        1
    ) AS next_order_id
FROM orders
\gset

SELECT
    GREATEST(
        COALESCE(MAX(order_item_id)::bigint, 0) + 1,
        1
    ) AS next_order_item_id
FROM order_items
\gset

SELECT
    GREATEST(
        COALESCE(MAX(log_id)::bigint, 0) + 1,
        1
    ) AS next_log_id
FROM inventory_log
\gset

-- Display calculated starting values.

\echo Orders starting ID: :next_order_id
\echo Order items starting ID: :next_order_item_id
\echo Inventory log starting ID: :next_log_id

-- Enable automatic identifier generation.

ALTER TABLE orders
    ALTER COLUMN order_id
    ADD GENERATED BY DEFAULT AS IDENTITY
    (START WITH :next_order_id);

ALTER TABLE order_items
    ALTER COLUMN order_item_id
    ADD GENERATED BY DEFAULT AS IDENTITY
    (START WITH :next_order_item_id);

ALTER TABLE inventory_log
    ALTER COLUMN log_id
    ADD GENERATED BY DEFAULT AS IDENTITY
    (START WITH :next_log_id);

COMMIT;