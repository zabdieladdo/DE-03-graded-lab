CREATE OR REPLACE FUNCTION public.audit_stock_update()
RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
DECLARE v_log_id integer;
BEGIN
    IF OLD.stock_quantity IS NULL OR NEW.stock_quantity IS NULL THEN
        RAISE EXCEPTION 'Cannot audit a movement with unknown stock quantity';
    END IF;
    INSERT INTO public.inventory_log(product_id,change_qty,reason,created_at,note,stock_before,stock_after,changed_by)
    VALUES (NEW.product_id, NEW.stock_quantity - OLD.stock_quantity, 'correction',
            clock_timestamp(), 'Direct stock update (no business reference supplied)',
            OLD.stock_quantity, NEW.stock_quantity, session_user)
    RETURNING log_id INTO v_log_id;
    -- Pointer only: never used to suppress logging. Each changed row gets a log.
    PERFORM set_config('kloudkart.last_stock_log_id',v_log_id::text,true);
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_audit_stock_update ON public.products;
CREATE TRIGGER trg_audit_stock_update AFTER UPDATE ON public.products
FOR EACH ROW WHEN (OLD.stock_quantity IS DISTINCT FROM NEW.stock_quantity)
EXECUTE FUNCTION public.audit_stock_update();
CREATE OR REPLACE FUNCTION public.place_order(p_customer_id bigint, p_product_id bigint, p_quantity integer)
 RETURNS TABLE(success boolean, order_id bigint, message text)
 LANGUAGE plpgsql
 SET search_path TO 'pg_catalog', 'public'
AS $function$

DECLARE
    v_order_id integer;
    v_log_id integer;
    v_unit_price numeric(12, 2);
    v_total_amount numeric(12, 2);

BEGIN

    -- 1. Validate the requested quantity.

    IF p_quantity IS NULL OR p_quantity <= 0 THEN

        RETURN QUERY
        SELECT
            false,
            NULL::bigint,
            'Quantity must be positive'::text;

        RETURN;

    END IF;


    -- 2. Validate the customer.
    --
    -- KEY SHARE prevents deletion or modification
    -- of the referenced customer key until the
    -- caller's transaction finishes.

    PERFORM c.customer_id
    FROM public.customers AS c
    WHERE c.customer_id = p_customer_id
    FOR KEY SHARE;

    IF NOT FOUND THEN

        RETURN QUERY
        SELECT
            false,
            NULL::bigint,
            'Customer not found'::text;

        RETURN;

    END IF;


    -- 3. Atomically check and deduct stock.
    --
    -- PostgreSQL coordinates concurrent updates
    -- to the same product row.
    --
    -- RETURNING captures the price associated
    -- with the successfully updated row.
    --
    -- The monetary guard prevents a purchase
    -- total exceeding NUMERIC(12,2).

    UPDATE public.products AS p
    SET stock_quantity =
        p.stock_quantity - p_quantity

    WHERE p.product_id = p_product_id
        AND p.stock_quantity >= p_quantity
        AND p.price >= 0
        AND p.price * p_quantity <= 9999999999.99

    RETURNING p.price
    INTO v_unit_price;


    -- 4. Handle unsuccessful stock allocation.
    --
    -- No purchase records have been created.
    -- This diagnostic lookup does not authorize
    -- a purchase or perform another deduction.

    IF NOT FOUND THEN

        IF NOT EXISTS (
            SELECT 1
            FROM public.products AS p
            WHERE p.product_id = p_product_id
        ) THEN

            RETURN QUERY
            SELECT
                false,
                NULL::bigint,
                'Product not found'::text;

        ELSE

            RETURN QUERY
            SELECT
                false,
                NULL::bigint,
                'Out of stock or product unavailable for requested quantity'::text;

        END IF;

        RETURN;

    END IF;


    -- Capture the exact audit row generated by the stock update.
    v_log_id := current_setting('kloudkart.last_stock_log_id')::integer;

    -- 5. Calculate the recorded purchase total.

    v_total_amount :=
        v_unit_price * p_quantity;


    -- 6. Create the order.
    --
    -- The identity column generates the ID.
    -- The recorded status is a documented
    -- lab assumption, not payment verification.

    INSERT INTO public.orders AS o (
        customer_id,
        order_date,
        status,
        total_amount
    )
    VALUES (
        p_customer_id,
        CURRENT_TIMESTAMP,
        'completed',
        v_total_amount
    )
    RETURNING o.order_id
    INTO v_order_id;


    -- 7. Create the corresponding order item.

    INSERT INTO public.order_items (
        order_id,
        product_id,
        quantity,
        unit_price
    )
    VALUES (
        v_order_id,
        p_product_id,
        p_quantity,
        v_unit_price
    );


    -- Enrich the existing trigger-generated movement; never insert a duplicate.
    UPDATE public.inventory_log AS l
    SET reason = 'sale', note = format('Order ID: %s', v_order_id)
    WHERE l.log_id = v_log_id AND l.product_id = p_product_id
      AND l.change_qty = -p_quantity AND l.reason = 'correction';
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Missing or inconsistent sale audit movement';
    END IF;

    -- 9. Return exactly one successful result.

    RETURN QUERY
    SELECT
        true,
        v_order_id::bigint,
        'Order placed successfully'::text;

    RETURN;

END;

$function$;

-- Signed delta, with explicit reason and explanation. Expected refusals return false.
CREATE OR REPLACE FUNCTION public.adjust_stock(p_product_id bigint,p_delta integer,p_reason text,p_note text)
RETURNS TABLE(success boolean,log_id bigint,message text)
LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
DECLARE v_log_id integer;
BEGIN
    IF p_delta IS NULL OR p_delta=0 OR p_reason IS NULL OR p_reason NOT IN ('restock','correction')
       OR (p_reason='restock' AND p_delta<0) OR NULLIF(btrim(p_note),'') IS NULL THEN
        RETURN QUERY SELECT false,NULL::bigint,'Invalid stock movement or missing explanation'::text; RETURN;
    END IF;
    UPDATE public.products AS p SET stock_quantity=(p.stock_quantity::bigint+p_delta)::integer
    WHERE p.product_id=p_product_id AND p.stock_quantity::bigint+p_delta BETWEEN 0 AND 2147483647;
    IF NOT FOUND THEN
        RETURN QUERY SELECT false,NULL::bigint,'Product unavailable or resulting stock outside valid range'::text; RETURN;
    END IF;
    v_log_id := current_setting('kloudkart.last_stock_log_id')::integer;
    UPDATE public.inventory_log AS l SET reason=p_reason,note=p_note
    WHERE l.log_id=v_log_id AND l.product_id=p_product_id AND l.change_qty=p_delta AND l.reason='correction';
    IF NOT FOUND THEN RAISE EXCEPTION 'Missing or inconsistent adjustment audit movement'; END IF;
    RETURN QUERY SELECT true,v_log_id::bigint,'Stock movement recorded'::text;
END $$;
COMMENT ON FUNCTION public.adjust_stock(bigint,integer,text,text) IS 'Atomic signed adjustment with mandatory explanation; restock positive only.';
COMMENT ON FUNCTION public.audit_stock_update() IS 'Logs each changed existing stock value; initial stock and deletion are outside movement scope.';
COMMIT;
